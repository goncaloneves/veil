const KNOWN: ReadonlySet<string> = new Set(ENVIRONMENT_KEYS)
const SECRET_FILE = /_(?:PASSWORD|PASSWD|PASSPHRASE|TOKEN|SECRET|KEY|CREDENTIALS?)_FILE$/

export function parseEnviron(text: string): Record<string, string> {
  const vars: Record<string, string> = {}
  for (const item of text.split('\0')) {
    const eq = item.indexOf('=')
    if (eq > 0) vars[item.slice(0, eq)] = item.slice(eq + 1)
  }
  return vars
}

export function secretFileVariables(vars: Readonly<Record<string, string | undefined>>): [string, string][] {
  return Object.entries(vars).filter((entry): entry is [string, string] => typeof entry[1] === 'string' && SECRET_FILE.test(entry[0]) && !/PUBLIC|PUBKEY/i.test(entry[0]) && isAbsolutePath(entry[1]) && !/\.(?:pub|crt|cer)$/i.test(entry[1]))
}

export function environmentSecrets(vars: Readonly<Record<string, string | undefined>>, policy: EnvPolicy): Secret[] {
  const entries: EnvEntry[] = []
  for (const [key, value] of Object.entries(vars)) if (typeof value === 'string' && value) entries.push({ key, value, literal: true })
  return envEntrySecrets(entries, 'environment', { ...policy, random: false, known: KNOWN })
}
